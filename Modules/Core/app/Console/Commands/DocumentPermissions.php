<?php

namespace Modules\Core\Console\Commands;

use Illuminate\Console\Command;
use Modules\Core\Database\Seeders\RolePermissionSeeder;
use Modules\Core\Support\PermissionCatalogue;

/**
 * Writes docs/api/permissions.md from the code: every permission, the endpoints
 * it guards and which seeded roles hold it. Generated, never hand-edited — run it
 * after adding or changing an endpoint.
 */
class DocumentPermissions extends Command
{
    protected $signature = 'permissions:docs {--path=docs/api/permissions.md : Where to write the file}';

    protected $description = 'Generate the permission reference (docs/api/permissions.md) from the routes and seeded roles';

    /** Seeded role => short column heading. */
    private const ROLE_HEADINGS = [
        'Administrator' => 'Adm', 'Owner' => 'Own', 'Sales Manager' => 'SM', 'Sales Rep' => 'SR', 'Warehouse Manager' => 'WM',
        'Warehouse Employee' => 'WE', 'Accountant' => 'Acc', 'Customer Service' => 'CS', 'Purchasing' => 'Pur',
        'HR Manager' => 'HR', 'Employee' => 'Emp', 'Auditor' => 'Aud',
    ];

    public function handle(): int
    {
        $roles = RolePermissionSeeder::expandedRoles();
        $catalogue = PermissionCatalogue::all();

        $lines = [
            '# Permission reference',
            '',
            '> Generated by `php artisan permissions:docs` from the routes and the seeded roles — do not edit by hand.',
            '',
            "Every API endpoint is guarded by **one permission**, named `{resource}.{action}` (for example `expenses.view`, `expense-categories.create`, `sales-orders.change-status`). {$catalogue->count()} permissions in all.",
            '',
            '- `view` covers every read of that resource: the list, one record, its nested lists, file downloads.',
            '- `create` / `update` / `delete` are the POST / PUT / DELETE of the resource; other verbs get their own action (`approve`, `receive`, `void`, `pay`, ...).',
            '- A list that can also be downloaded (`?export=csv|xlsx`) has a separate `{resource}.export` permission, needed in addition to `view`.',
            '- Giving a role `expenses.view` but not `expense-categories.view` lets its users read expenses and not the expense categories: permissions are per resource, not per module.',
            '- `Administrator` holds every permission and is not subject to the checks.',
            '- Open to any signed-in user (no permission): `POST /auth/logout`, `GET /auth/me`, `POST /auth/change-password`, the user\'s own `notifications`, the `governorates` / cities lists and `POST /discarded-actions`. `POST /auth/login` is public.',
            '- `GET /api/v1/permissions` returns this same catalogue (grouped by module and resource, with the endpoints of each); `PUT /api/v1/roles/{id}` sets a role\'s permissions.',
            '',
            'Role columns: '.collect(self::ROLE_HEADINGS)->map(fn ($short, $role) => "**{$short}** = {$role}")->implode(', ').'.',
            '',
        ];

        foreach ($catalogue->groupBy('module')->sortKeys() as $module => $entries) {
            $lines[] = '## '.ucfirst($module);
            $lines[] = '';
            $lines[] = '| Permission | Guards | '.implode(' | ', self::ROLE_HEADINGS).' |';
            $lines[] = '|---|---|'.str_repeat('---|', count(self::ROLE_HEADINGS));

            foreach ($entries->sortBy('permission') as $entry) {
                $marks = collect(self::ROLE_HEADINGS)->map(fn ($short, $role) => in_array($entry['permission'], $roles[$role] ?? [], true) ? '✓' : '')->implode(' | ');
                $endpoints = collect($entry['endpoints'])->map(fn (string $e) => '`'.str_replace('/api/v1', '', $e).'`')->implode('<br>');

                $lines[] = "| `{$entry['permission']}` | {$endpoints} | {$marks} |";
            }

            $lines[] = '';
        }

        file_put_contents(base_path($this->option('path')), implode("\n", $lines));
        $this->info("Wrote {$catalogue->count()} permissions to {$this->option('path')}.");

        return self::SUCCESS;
    }
}
